"""Build a deterministic, secret-free source bundle into the SSH stdin installer."""
from __future__ import annotations
import base64
import hashlib
import io
import json
from pathlib import Path
import zipfile

ROOT=Path(__file__).resolve().parents[2]


def source_paths(root=ROOT):
    files=list((root/'src/trendatlas_clean').glob('*.py'))
    files+=list((root/'tests').glob('test_clean_5050*.py'))
    files+=list((root/'tests/fixtures').glob('clean_5050*'))
    files+=[root/p for p in (
        'requirements-clean-5050.txt','requirements-clean-execution.txt',
        'scripts/production/run_clean_5050.py','scripts/production/execute_clean_5050.py',
        'scripts/production/disable_phase68g.py','scripts/production/build_clean_installer.py',
        'deploy/clean_5050/bootstrap_multi_account.py','scripts/research/fetch_clean_5050_data.py',
        'scripts/research/validate_clean_5050.py','execution/config/clean_5050_policy.json',
        'source_of_truth/clean_5050_contract.json','source_of_truth/clean_5050_asset_exclusions.json',
        'deploy/systemd/trendatlas-clean-production.service','deploy/systemd/trendatlas-clean-production.timer')]
    files += [root/'scripts/production/run_clean_multi_account.py', root/'app.py']
    files += [p for p in (root/'web/src').rglob('*') if p.is_file()]
    files += [p for d in ('scripts', 'tests', 'supabase/migrations') for p in (root/'web'/d).rglob('*') if p.is_file()]
    files += [root/'web'/n for n in ('package.json','package-lock.json','tsconfig.json','vitest.config.ts','next.config.ts','next-env.d.ts','eslint.config.mjs','.env.example')]
    return sorted(set(p for p in files if p.is_file()))


def bundle(root=ROOT):
    buf=io.BytesIO();manifest={}
    with zipfile.ZipFile(buf,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as archive:
        for path in source_paths(root):
            name=path.relative_to(root).as_posix();body=path.read_bytes()
            manifest[name]=hashlib.sha256(body).hexdigest()
            zi=zipfile.ZipInfo(name,(2026,10,18,0,0,0));zi.compress_type=zipfile.ZIP_DEFLATED;zi.external_attr=0o100644<<16
            archive.writestr(zi,body)
        zi=zipfile.ZipInfo('BUNDLE_MANIFEST.json',(2026,10,18,0,0,0));zi.compress_type=zipfile.ZIP_DEFLATED;zi.external_attr=0o100644<<16
        archive.writestr(zi,json.dumps(manifest,sort_keys=True,indent=2).encode()+b'\n')
    return buf.getvalue(),manifest


def build(root=ROOT):
    body,manifest=bundle(root);digest=hashlib.sha256(body).hexdigest()
    runtime=(root/'deploy/clean_5050/bootstrap_multi_account.py').read_text()
    prelude='# Generated by scripts/production/build_clean_installer.py; contains source, never credentials.\n'
    prelude+='BUNDLE_B64='+repr(base64.b64encode(body).decode())+'\nBUNDLE_SHA256='+repr(digest)+'\nRUNTIME_SOURCE='+repr(runtime)+'\n'
    target=root/'deploy/clean_5050/install_multi_account.py'
    target.write_text(prelude+'exec(compile(RUNTIME_SOURCE,"bootstrap_runtime","exec"))\n')
    (root/'deploy/clean_5050/bundle_manifest.json').write_text(json.dumps({'bundle_sha256':digest,'files':manifest},indent=2)+'\n')
    return {'path':str(target),'bundle_sha256':digest,'file_count':len(manifest),'installer_bytes':target.stat().st_size}


if __name__=='__main__':print(json.dumps(build()))
